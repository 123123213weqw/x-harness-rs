import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
import {patchPermissionSelection} from './patch-permission-selection.mjs';
import { verifyConversationArtifact, exposeConversation, legacyConversation } from './conversation-artifact-test.mjs';
import { harness } from './conversation-test-harness.mjs';
import { testHooks, descendants, barFixture } from './conversation-test-hooks.mjs';
const s=verifyConversationArtifact();
const golden=legacyConversation();assert.deepEqual(patchPermissionSelection(golden),golden,'retained patch golden stays idempotent');
const hooks=testHooks();
const {plugin}=harness(exposeConversation(s,['PermissionSelect','permissionFeedback','InputBar']),{react:hooks.react,jsx:hooks.jsx,globals:{navigator:{userAgent:'test',vendor:''}}});
const component=plugin.PermissionSelect,feedback=plugin.permissionFeedback;
assert.equal(feedback({pending:false}),'');
assert.match(feedback({pending:true,activeValue:'workspace-write'}),/下一轮.*workspace-write/);
assert.match(feedback({pending:true,activeValue:'danger-full-access'}),/立即收紧请停止/);
assert.match(feedback({pending:true}),/正在准备/);
let commands=[];
let value={currentValue:'workspace-write',activeValue:'workspace-write',pending:false,options:[{value:'workspace-write',name:'Workspace'},{value:'danger-full-access',name:'Full'}]};
let resolve;
const command=x=>{commands.push(x);return new Promise(r=>{resolve=r;});};
const render=(locked=false)=>{return hooks.render(()=>component({value,locked,command,t:x=>x})).props.children;};
let [menu]=render();assert.equal(menu.props.anchor.props.disabled,false);
menu.props.onSelect('danger-full-access');
let [,confirmation]=render();assert.equal(confirmation.props.open,true);assert.equal(commands.length,0,'full access still requires confirmation');
confirmation.props.onConfirm();assert.equal(commands.length,0,'unacknowledged confirmation cannot submit');
confirmation.props.onAcknowledgedChange(true);[,confirmation]=render();confirmation.props.onConfirm();
assert.deepEqual(commands,['/permission danger-full-access']);
[menu]=render();assert.equal(menu.props.anchor.props.disabled,true);assert.match(menu.props.anchor.props.title,/正在保存/);
// A failed/rejected command does not mutate the host's selected value.
resolve(false);await new Promise(r=>setImmediate(r));
[menu]=render();assert.equal(menu.props.selectedId,'workspace-write');
value={...value,currentValue:'danger-full-access',pending:true};
[menu]=render();assert.equal(menu.props.selectedId,'danger-full-access');assert.match(menu.props.anchor.props.title,/当前轮：workspace-write/);
assert.equal(render(true)[0].props.anchor.props.disabled,true,'read-only/locked contexts remain locked');
// AI review is a distinct Host option, not an alias for Full access.
value={...value,currentValue:'workspace-write-ai-review',options:[...value.options,{value:'workspace-write-ai-review',name:'AI review'}]};
[menu]=render();assert.equal(menu.props.selectedId,'workspace-write-ai-review');
const aiIcon=menu.props.items.find(item=>item.id==='workspace-write-ai-review').icon;
assert.ok(aiIcon,'the Host AI review preset must have a leading menu icon');
assert.equal(aiIcon.type,'svg');assert.equal(aiIcon.props['aria-hidden'],true);
assert.equal(aiIcon.props.viewBox,'0 0 16 16');
assert.ok(descendants(menu.props.anchor,node=>node===aiIcon).length,'selected AI review must reuse the same glyph in the trigger');
assert.notDeepEqual(aiIcon,menu.props.items.find(item=>item.id==='danger-full-access').icon,'AI review must not use the Full access warning glyph');
for(const option of value.options)assert.ok(menu.props.items.find(item=>item.id===option.value).icon,`built-in preset ${option.value} has a glyph`);
const knownValue=value;
value={...value,currentValue:'vendor-mode',options:[...value.options,{value:'vendor-mode',name:'Vendor Mode'},{value:'custom',name:'Custom'}]};
[menu]=render();assert.equal(menu.props.items.find(item=>item.id==='vendor-mode').icon,undefined,'unknown presets do not inherit the AI icon');
assert.equal(menu.props.items.some(item=>item.id==='custom'),false,'Custom stays display-only');
value=knownValue;[menu]=render();
menu.props.onSelect('workspace-write');
assert.equal(commands.at(-1),'/permission workspace-write');
resolve(true);await new Promise(r=>setImmediate(r));
value={...value,currentValue:'workspace-write'};
[menu]=render();menu.props.onSelect('workspace-write-ai-review');
assert.equal(commands.at(-1),'/permission workspace-write-ai-review');
resolve(true);await new Promise(r=>setImmediate(r));
