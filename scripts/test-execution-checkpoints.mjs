import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {patchExecutionCheckpoints} from './patch-execution-checkpoints.mjs';
const helper=readFileSync(new URL('../ui/overrides/execution-checkpoints.js',import.meta.url),'utf8');
const env={react:{memo:x=>x},chatNode:(_c,kind,seq,data)=>({kind,seq,data})};
vm.runInNewContext(helper+'\nglobalThis.definition=xhCheckpointDefinition;',env);
const d=env.definition;
const event={seq:42,time:1,type:'run/checkpoint',data:{turn:0,notice:{kind:'issued',message:'阶段及重复提醒',phase:1}}};
assert.equal(d.match(event).id,'42');
const live=d.start({}, {event});const restored=d.start({}, {event:JSON.parse(JSON.stringify(event))});
assert.deepEqual(live,restored);
assert.equal(d.buildViewNode({state:live}).data.noticeKind,'issued');
assert.equal(d.match({...event,data:{turn:0,notice:null}}),null);
assert.equal(d.match({type:'turn/end',data:{turn:0,reason:{kind:'completed'}}}),null);
assert.equal(d.start({}, {event:{...event,type:'turn/end',data:{turn:0,reason:{kind:'max-steps'}}}}).kind,'limit');
const bundle=readFileSync(new URL('../ui/dist/plugins/@deepseek-ai/dsh-client-ui-conversation/client.js',import.meta.url));
assert.deepEqual(patchExecutionCheckpoints(bundle),bundle);
assert.ok(bundle.toString().includes(helper.trim()));
assert.ok(bundle.toString().includes('ctx.conversationEvents.register(xhCheckpointDefinition)'));
assert.ok(bundle.toString().includes('key:"run-checkpoint"'));
assert.throws(()=>patchExecutionCheckpoints(Buffer.from('changed upstream')),/anchor changed/);
console.log('execution checkpoint: live/history projection, limit notice, hidden snapshots, registrations and patch idempotence passed');
