/** Same-run build reuse only, never an across-commit compiler cache. */
import assert from 'node:assert/strict'
import { lstatSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { sha256, treeHashes } from './ui-build-contract.mjs'
export function receipt(root, sourceSha) {
  assert.match(sourceSha, /^[0-9a-f]{40}$/, 'A full checkout SHA is required')
  assert.ok(lstatSync(resolve(root, 'ui/dist')).isDirectory(), 'Generated UI root must be a real directory, not a symlink')
  return { schemaVersion: 1, sourceSha, planSha256: sha256(readFileSync(resolve(root, 'scripts/ci/ui-plan.json'))), files: treeHashes(resolve(root, 'ui/dist')) }
}
export function verify(root, expected, sourceSha) {
  assert.deepEqual(expected, receipt(root, sourceSha), 'UI artifact must match this checkout SHA, plan and every generated byte')
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [mode, path] = process.argv.slice(2)
  assert.ok(['--write', '--verify'].includes(mode) && path, 'Usage: ci-ui-artifact.mjs --write|--verify RECEIPT')
  const root = fileURLToPath(new URL('../', import.meta.url))
  if (mode === '--write') writeFileSync(path, JSON.stringify(receipt(root, process.env.GITHUB_SHA), null, 2) + '\n')
  else verify(root, JSON.parse(readFileSync(path)), process.env.GITHUB_SHA)
}
