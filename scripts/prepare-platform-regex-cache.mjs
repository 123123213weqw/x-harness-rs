// Reproducible acceleration, not a different grammar/engine. Original pattern
// strings stay in TextMate so interpolation and runtime cache misses still work.
import {createRequire} from 'node:module'
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs'
import {dirname, resolve, join} from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'
import {createHash} from 'node:crypto'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'ui/package.json'))
export const cacheLanguages = ['typescript', 'shellscript', 'json']
export async function preparedCacheSources() {
  const {defaultJavaScriptRegexConstructor} = await import(pathToFileURL(require.resolve('shiki/engine/javascript')))
  const result = new Map()
  for (const language of cacheLanguages) {
    const path = require.resolve(`@shikijs/langs/${language}`)
    const {default: grammars} = await import(pathToFileURL(path))
    const patterns = new Set()
    function collect(value) {
      if (!value || typeof value !== 'object') return
      for (const [key, child] of Object.entries(value)) {
        if (['match', 'begin', 'end', 'while'].includes(key) && typeof child === 'string') patterns.add(child)
        else collect(child)
      }
    }
    collect(grammars)
    for (const target of ['ES2018']) {
      const entries = []
      for (const pattern of [...patterns].sort()) {
        try {
          // Use the exact upstream constructor/rules, not a second copy of its
          // converter defaults. Native compilation remains lazy until scanned.
          const regex = defaultJavaScriptRegexConstructor(pattern, {target, lazyCompileLength: Infinity})
          entries.push([pattern, regex.source, regex.flags, {...regex.rawOptions, lazyCompile: true}])
        } catch {
          // Original forgiving engine owns unsupported/dynamic pattern misses.
        }
      }
      const hash = createHash('sha256').update(readFileSync(path)).digest('hex')
      const name = `${language}-${target.toLowerCase()}.ts`
      const text = `// GENERATED by scripts/prepare-platform-regex-cache.mjs --write; do not edit.\n// Original pinned @shikijs/langs/${language}: ${hash}\n// Derived via the pinned Shiki JS engine; grammar licenses remain in ui/platform-npm-provenance.json.\nimport type {CompiledPattern} from './types'\nexport const entries: readonly CompiledPattern[] = ${JSON.stringify(entries)}\n`
      result.set(name, text)
    }
  }
  return result
}
export async function verifyPreparedCaches({write = false} = {}) {
  const folder = join(root, 'ui/src/modules/platform/primitives/markdown/regex-cache')
  const sources = await preparedCacheSources()
  if (write) mkdirSync(folder, {recursive:true})
  for (const [name, source] of sources) {
    if (write) writeFileSync(join(folder,name), source)
    else if (readFileSync(join(folder,name),'utf8') !== source) throw Error(`Stale syntax conversion cache: ${name}; regenerate on a development/build server`)
  }
  return sources.size
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`${await verifyPreparedCaches({write:process.argv.includes('--write')})} pinned syntax conversion caches verified`)
}
