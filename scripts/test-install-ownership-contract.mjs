import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const native = 'apps/desktop/src-tauri/'
const lib = read(native + 'src/lib.rs')
const stop = read(native + 'src/sidecar.rs')
const update = read(native + 'src/updater.rs')
const script = read(native + 'windows/install-ownership.ps1')
const hooks = read(native + 'windows/hooks.nsh')
assert.ok(lib.indexOf('tauri_plugin_single_instance::init') < lib.indexOf('tauri_plugin_shell::init'))
assert.match(stop, /new_kill_on_close/)
assert.match(stop, /host_job.assign_pid/)
assert.match(stop, /active_processes\s*!= 0/)
const stopFailure = update.slice(update.indexOf('if let Err(error) = sidecar::graceful_stop'), update.indexOf('update.install(bytes.as_slice())'))
assert.match(stopFailure, /return fail\(/)
assert.match(update, /clear_installer_args\(\)/)
assert.match(update, /OsString::from\("\/D="\)/)
assert.equal(JSON.parse(read(native + 'tauri.conf.json')).identifier, 'com.xlang.xharness')
assert.match(hooks, /NSIS_HOOK_PREINSTALL/)
assert.match(hooks, /NSIS_HOOK_POSTINSTALL/)
assert.doesNotMatch(script + hooks, /Stop-Process|taskkill|Set-ExecutionPolicy|ExecutionPolicy\s+Bypass/i)
assert.deepEqual(script.match(/^\s*Remove-Item\b.*$/gm)?.map(line => line.trim()), [
  'Remove-Item -LiteralPath $legacy -ErrorAction Stop',
])
assert.match(script, /installer-backups/)
assert.match(script, /Save-XHarnessShortcutBackup \$record.Link \$version/)
assert.doesNotMatch(script, /Copy-Item -LiteralPath \$record.Link/)
assert.ok(script.indexOf('$hash = Save-XHarnessShortcutBackup $legacy') < script.indexOf('Remove-Item -LiteralPath $legacy'))
assert.match(script, /GetOwnerSid/)
assert.match(script, /before-xharness-update/)
assert.match(script, /FFFF0FFF/)
assert.match(script, /record.Custom/)
assert.match(read('scripts/test-windows-install-ownership.ps1'), /github-hosted/)
console.log('Installation ownership contracts passed (native runtime acceptance remains separate).')

