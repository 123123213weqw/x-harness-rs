/**
 * Render a state dot.
 * @param props.state - which of the four states to show.
 * @param props.size - outer diameter in px (default 10, the figma size).
 * @param props.className - extra class for layout placement.
 * @returns the dot element (aria-hidden; pair with text for accessibility).
 */
export function StateDot({ state, size = 10, className }: {
  state: StateDotState
  size?: number | undefined
  className?: string | undefined
}) {
  if (state === 'ongoing') {
    return (
      <svg
        className={clsx(css.ongoing, className)}
        data-state="ongoing"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="3"
        strokeLinecap="square"
        aria-hidden="true"
      >
        <path className={css.bracketLeft} d="M8 21H5a1 1 0 0 1-1-1V4a1 1 0 0 1 1-1h3" />
        <path className={css.bracketRight} d="M16 3h3a1 1 0 0 1 1 1v16a1 1 0 0 1-1 1h-3" />
        <rect className={css.node} x="9" y="9" width="6" height="6" stroke="none" />
      </svg>
    )
  }
  return (
    <span
      className={clsx(css.dot, className)}
      data-state={state}
      style={{ width: size, height: size }}
      aria-hidden="true"
    />
  )
}
